                ${feature.body}
              </div>
            </div>
          </div>`;
      }

      document.querySelectorAll('.feature-learn-more-btn').forEach(function (btn) {
        btn.addEventListener('click', function () {
          const key = this.getAttribute('data-feature');
          const feature = featureDetails[key];
          modalContent.innerHTML = feature ? renderFeature(feature) : '<p class="p-8">No details available for this feature.</p>';
          modal.classList.remove('hidden');
          modal.classList.add('flex');
          modalBox.scrollTop = 0;
          goToTopBtn.classList.add('hidden');
        });
      });

      function closeFeatureModal() {
        modal.classList.add('hidden');
        modal.classList.remove('flex');
      }

      closeModalBtn.addEventListener('click', closeFeatureModal);
      modal.addEventListener('click', function (e) {
        if (e.target === modal) closeFeatureModal();
      });
      document.addEventListener('keydown', function (e) {
        if (e.key === 'Escape' && !modal.classList.contains('hidden')) closeFeatureModal();
      });

      modalBox.addEventListener('scroll', function () {
        if (modalBox.scrollTop > 100) {
          goToTopBtn.classList.remove('hidden');
        } else {
          goToTopBtn.classList.add('hidden');
        }
      });
      goToTopBtn.addEventListener('click', function () {
        modalBox.scrollTo({ top: 0, behavior: 'smooth' });
      });
    });
