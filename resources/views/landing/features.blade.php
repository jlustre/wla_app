      };

      function renderFeature(feature) {
        const a = accentClasses[feature.accent] || accentClasses.emerald;
        return `
          <div class="rounded-lg bg-white dark:bg-slate-900">
            <div class="flex items-center gap-4 border-b border-slate-100 px-6 py-5 dark:border-slate-800 sm:px-8">
