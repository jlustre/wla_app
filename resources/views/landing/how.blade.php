    <!-- Go to Top button logic -->
    <script>
      document.addEventListener('DOMContentLoaded', function () {
        const stepContents = @json($stepContents);
        const modal = document.getElementById('learnMoreModal');
        const modalContent = document.getElementById('modalContent');
        const closeModalBtn = document.getElementById('closeModalBtn');
        document.querySelectorAll('.learn-more-btn').forEach(btn => {
          btn.addEventListener('click', function () {
            const step = this.getAttribute('data-step');
            modalContent.innerHTML = stepContents[step] || '<p>No details available for this step.</p>';
            modal.classList.remove('hidden');
            // Reset scroll and hide Go to Top button on open
            modalBox.scrollTop = 0;
            goToTopBtn.classList.add('hidden');
          });
        });
        closeModalBtn.addEventListener('click', function () {
          modal.classList.add('hidden');
        });
        modal.addEventListener('click', function (e) {
          if (e.target === modal) modal.classList.add('hidden');
        });

        // Go to Top button logic
        const goToTopBtn = document.getElementById('goToTopBtn');
        const modalBox = modal.querySelector('div.bg-white');
        modalBox.addEventListener('scroll', function () {
          if (modalBox.scrollTop > 100) {
            goToTopBtn.classList.remove('hidden');
          } else {
            goToTopBtn.classList.add('hidden');
          }
        });
        goToTopBtn.addEventListener('click', function () {
          modalBox.scrollTo({ top: 0, behavior: 'smooth' });
        });
      });
    </script>
